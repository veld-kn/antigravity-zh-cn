  const TRANSLATABLE_ATTRS = ['placeholder', 'title', 'aria-label', 'alt', 'value'];

  /**
   * 翻译元素本身及其直接文本
   */
  function translateElement(el) {
    if (!el) return;
    const tag = el.tagName ? el.tagName.toLowerCase() : '';
    if (['script', 'style', 'code', 'pre', 'svg', 'math', 'noscript'].includes(tag)) return;

    // 翻译直接子文本节点
    if (el.childNodes) {
      for (let i = 0; i < el.childNodes.length; i++) {
        const node = el.childNodes[i];
        if (node && node.nodeType === TEXT_NODE) {
          const translated = translateText(node.textContent);
          if (translated && translated !== node.textContent) {
            node.textContent = translated;
          }
        }
      }
    }

    // 翻译关键属性
    if (typeof el.getAttribute === 'function' && typeof el.setAttribute === 'function') {
      for (const attr of TRANSLATABLE_ATTRS) {
        if (attr === 'value' && (tag === 'textarea' || (tag === 'input' && !['button', 'submit', 'reset'].includes(el.type)))) {
          continue;
        }
        const val = el.getAttribute(attr);
        if (val) {
          const translated = translateText(val);
          if (translated && translated !== val) {
            el.setAttribute(attr, translated);
          }
        }
      }
    }

    // 穿透 Shadow DOM
    if (el.shadowRoot) {
      translateSubtree(el.shadowRoot);
    }
  }

  /**
   * 深度递归遍历子树
   */
  function translateSubtree(root) {
    if (!root) return;
    if (root.nodeType === ELEMENT_NODE) {
      translateElement(root);
    }
    if (typeof document === 'undefined' || typeof document.createTreeWalker !== 'function') return;

    try {
      const walker = document.createTreeWalker(
        root,
        SHOW_ELEMENT,
        {
          acceptNode: (node) => {
            const tag = node.tagName ? node.tagName.toLowerCase() : '';
            if (['script', 'style', 'code', 'pre', 'svg', 'math', 'textarea'].includes(tag)) {
              return FILTER_REJECT;
            }
            return FILTER_ACCEPT;
          }
        }
      );
      let current = walker.nextNode();
      while (current) {
        translateElement(current);
        current = walker.nextNode();
      }
    } catch (_) {}
  }

  // =====================================================================
  // MutationObserver — 实时增量翻译
  // =====================================================================
  let observer = null;
  let pendingFrame = null;
  let pendingNodes = new Set();

  function processPending() {
    pendingFrame = null;
    const nodes = pendingNodes;
    pendingNodes = new Set();
    for (const node of nodes) {
      if (node.nodeType === TEXT_NODE) {
        const translated = translateText(node.textContent);
        if (translated && translated !== node.textContent) {
          node.textContent = translated;
        }
      } else if (node.nodeType === ELEMENT_NODE) {
        translateSubtree(node);
      }
    }
  }

  function scheduleBatch(node) {
    pendingNodes.add(node);
    if (!pendingFrame) {
      const raf = getRaf();
      pendingFrame = raf(processPending);
    }
  }

  function startObserver() {
    if (observer) return;
    if (typeof document === 'undefined') return;
    const target = document.documentElement || document.body;
    if (!target) {
      setTimeout(startObserver, 50);
      return;
    }

    const MO = getMO();
    if (!MO) return;

    try {
      observer = new MO((mutations) => {
        for (const mutation of mutations) {
          if (mutation.type === 'childList') {
            for (let i = 0; i < mutation.addedNodes.length; i++) {
              const node = mutation.addedNodes[i];
              if (node.nodeType === ELEMENT_NODE || node.nodeType === TEXT_NODE) {
                scheduleBatch(node);
              }
            }
          } else if (mutation.type === 'characterData') {
            scheduleBatch(mutation.target);
          } else if (mutation.type === 'attributes') {
            if (mutation.target.nodeType === ELEMENT_NODE) {
              scheduleBatch(mutation.target);
            }
          }
        }
      });

      observer.observe(target, {
        childList: true,
        subtree: true,
        characterData: true,
        attributes: true,
        attributeFilter: ['placeholder', 'title', 'aria-label', 'alt', 'value'],
      });
    } catch (e) {
      console.error('[zh-CN] Observer init error:', e);
    }
  }

  // =====================================================================
  // 启动与轮询兜底
  // =====================================================================
  function init() {
    if (typeof document !== 'undefined' && document.body) {
      translateSubtree(document.body);
    }
    startObserver();
  }

  if (typeof document !== 'undefined') {
    if (document.readyState === 'loading') {
      document.addEventListener('DOMContentLoaded', init);
    } else {
      const raf = getRaf();
      raf(init);
    }
  }

  if (typeof window !== 'undefined') {
    window.addEventListener('load', () => {
      const raf = getRaf();
      raf(() => {
        if (typeof document !== 'undefined' && document.body) translateSubtree(document.body);
      });
    });

    // 1.0 秒高频轮询兜底，专治 React 动态渲染、抽屉弹窗与设置切换
    setInterval(() => {
      if (typeof document !== 'undefined' && document.body) {
        translateSubtree(document.body);
      }
    }, 1000);
  }

